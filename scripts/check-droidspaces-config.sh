NETFILTER_XT_SET
NETFILTER_NETLINK_QUEUE
NETFILTER_NETLINK_LOG
NETFILTER_XT_TARGET_NFLOG
NF_CT_NETLINK
MEMCG_SWAP_ENABLED
REQUIRED

if [ "$missing" -ne 0 ]; then
    echo "Droidspaces: $missing required/recommended options missing" >&2
    exit 1
fi

echo "Droidspaces: 4.19 kernel configuration checks passed"
