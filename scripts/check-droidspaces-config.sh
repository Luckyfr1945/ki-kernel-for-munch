#!/bin/bash
# Check resolved Kconfig output, not an unprocessed defconfig.
# Requirements: ravindu644/Droidspaces-OSS@cdadb9eb5d0f
# See Documentation/droidspaces-upstream.md for 4.19 symbol mappings.
set -eu

if [ "$#" -ne 1 ] || [ ! -r "$1" ]; then
    echo "Usage: bash $0 <resolved .config>" >&2
    exit 2
fi

config_file=$1
missing=0
while IFS= read -r symbol; do
    if ! grep -qx "CONFIG_${symbol}=y" "$config_file"; then
        echo "Droidspaces: CONFIG_${symbol}=y is missing" >&2
        missing=$((missing + 1))
    fi
done <<'REQUIRED'
SYSCTL
SYSVIPC
POSIX_MQUEUE
NAMESPACES
PID_NS
UTS_NS
IPC_NS
SECCOMP
SECCOMP_FILTER
CGROUPS
CGROUP_DEVICE
CGROUP_SCHED
FAIR_GROUP_SCHED
CGROUP_FREEZER
CGROUP_NET_PRIO
MEMCG
MEMCG_SWAP
CFS_BANDWIDTH
CGROUP_PIDS
CGROUP_CPUACCT
DEVTMPFS
OVERLAY_FS
TMPFS_POSIX_ACL
TMPFS_XATTR
FW_LOADER
FW_LOADER_USER_HELPER
NET_NS
VETH
